"""SQLAlchemy adapter for developer-owned tables and SDK-owned sync metadata.

All participating tables must use the same transactional database. A singleton
metadata row serializes gateway writes, including sequence allocation, so a pull
cursor can never skip a late-committing change. This prioritizes correctness over
write throughput. Schema initialization is an explicit application/setup action.
"""

